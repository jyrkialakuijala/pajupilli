#!/usr/bin/env python3
"""The tension each string needs, measured from the tuned grand's sound.

Each key is rendered dry, alone and softly (no pitch rise from the blow). Its partials are found and
fitted to f_n^2 / n^2 = f0^2 (1 + B n^2), which gives f0, the frequency the string would have with
no stiffness, as it sounds on the bridge at its tuned pitch. The tension is then T = mu (2 L f0)^2.

Only the plain wire (keys 21-88) is a measurement: its mass per metre follows from its gauge. The
wound strings' mass is not known independently (the model derives it from the tension it is given),
so their row repeats the input and is marked so.

    tools/tension_table.py [--bin ./pajupilli] [--out research/piano_tension.md]
"""
import argparse
import math
import os
import re
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor

import numpy as np
from scipy.io import wavfile

KGF = 9.80665
RHO = 7850
NOTE = 'A A# B C C# D D# E F F# G G#'.split()


def note(key):
    return f'{NOTE[(key - 1) % 12]}{(key + 8) // 12}'


def scale():
    src = open('src/piano.cc', encoding='utf8').read()
    def table(name):
        at = src.index(name)
        return [float(x) for x in re.findall(r'\d+\.\d+', src[src.index('{', at):src.index('}', at)])]
    lengths, kgf = table('kLen[88]'), table('kKgf[88]')
    at = src.index('kWire[]')
    wire = [(int(a), float(b)) for a, b in re.findall(r'\{(\d+), ([\d.]+)\}', src[at:src.index('};', at)])]
    assert len(lengths) == 88 and len(kgf) == 88 and wire[-1][0] == 88
    return lengths, kgf, wire


def measure(job):
    binary, key, folder = job
    midi = key + 20
    path = os.path.join(folder, f'k{key}.wav')
    hold = 3.4 if key < 64 else 1.6
    subprocess.run([binary, '-inst', 'grand-piano', '-seq', f'on {midi} 45, wait {hold}, off {midi}, wait 0.02', '-o', path],
                   capture_output=True, check=True, env={**os.environ, 'PJ_PIANO_GLIDE': '0'})
    fs, x = wavfile.read(path)
    os.remove(path)
    x = (x.sum(1) if x.ndim > 1 else x).astype(float)
    start = int(np.argmax(np.abs(x) > np.abs(x).max() * 0.05))
    seg = x[start + int(0.15 * fs):start + int((hold - 0.1) * fs)]
    size = 1 << 21
    spec = np.abs(np.fft.rfft(seg * np.hanning(len(seg)), size))
    bin_hz = fs / size
    level = 20 * np.log10(spec + 1e-12)

    def peak(centre, width):
        lo, hi = max(int((centre - width) / bin_hz), 1), min(int((centre + width) / bin_hz), len(spec) - 2)
        if hi <= lo:
            return None
        j = lo + int(np.argmax(spec[lo:hi + 1]))
        a, b, c = level[j - 1:j + 2]
        shift = 0.5 * (a - c) / (a - 2 * b + c) if a - 2 * b + c else 0
        return (j + shift) * bin_hz, b

    nominal = 440 * 2 ** ((key - 49) / 12)
    first = peak(nominal, nominal * 0.04)
    top = level[int(20 / bin_hz):int(min(18000, fs / 2 - 100) / bin_hz)].max()
    points, f1, B = [], first[0], 2e-4
    for n in range(1, 17):
        guess = n * f1 * math.sqrt((1 + B * n * n) / (1 + B))
        if guess > 16000:
            break
        got = peak(guess, min(0.012 * guess, 0.3 * f1))
        if got and got[1] > top - 60:
            points.append((n, got[0]))
            if len(points) >= 3:  # (the stretch so far, for the next partial's place)
                ns = np.array([p[0] for p in points], float)
                ys = np.array([(p[1] / p[0]) ** 2 for p in points])
                slope, cut = np.polyfit(ns * ns, ys, 1)
                if cut > 0 and slope > 0:
                    B = slope / cut
    if len(points) >= 3:
        ns = np.array([p[0] for p in points], float)
        ys = np.array([(p[1] / p[0]) ** 2 for p in points])
        slope, cut = np.polyfit(ns * ns, ys, 1)
        return key, math.sqrt(cut), slope / cut, len(points), f1
    return key, None, None, len(points), f1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--bin', default='./pajupilli')
    ap.add_argument('--out', default='research/piano_tension.md')
    args = ap.parse_args()
    lengths, kgf, wire = scale()
    with tempfile.TemporaryDirectory() as folder, ThreadPoolExecutor(max(os.cpu_count() // 2, 2)) as pool:
        found = {r[0]: r for r in pool.map(measure, [(args.bin, k, folder) for k in range(1, 89)])}

    rows = ['# The grand\'s string tensions, measured from its tuned sound', '',
            'Generated by `tools/tension_table.py`. f0 is the stiffness-free frequency fitted to the sounding',
            'partials; plain-wire tension is `mu (2 L f0)^2` with the gauge\'s mass. Wound rows repeat the input',
            'tension, because their mass is derived from it. Keys with too few partials to fit are marked `-`.', '',
            '| Key | Note | Strings | Gauge | L (m) | Partials | f0 (Hz) | Pitch vs 12-TET (c) | B | Measured (kgf) | Pasted table (kgf) | Difference |',
            '|---|---|---|---|---|---|---|---|---|---|---|---|']
    plain, summary = [], {}
    total = 0
    for key in range(1, 89):
        _, f0, B, used, f1 = found[key]
        strings = 1 if key <= 8 else 2 if key <= 13 else 3
        nominal = 440 * 2 ** ((key - 49) / 12)
        L = lengths[key - 1]
        if key <= 20:
            total += kgf[key - 1] * strings
            rows.append(f'| {key} | {note(key)} | {strings} | wound | {L:.3f} | {used} | {f0 or f1:.3f} | '
                        f'{1200 * math.log2((f0 or f1) / nominal):+.1f} | {B or 0:.2e} | input | {kgf[key - 1]:.2f} | - |')
            continue
        gauge = next(g for last, g in wire if key <= last)
        d = (0.775 + (gauge - 13) * 0.05) * 1e-3
        mu = RHO * math.pi * d * d / 4
        if f0 is None:
            f0, fitted = f1, False  # (the top keys: their first partial, the little stretch left out)
        else:
            fitted = True
        T = mu * (2 * L * f0) ** 2 / KGF
        total += T * strings
        diff = 100 * (T / kgf[key - 1] - 1)
        plain.append((key, T, diff, fitted))
        rows.append(f'| {key} | {note(key)} | {strings} | #{gauge:g} | {L:.3f} | {used} | {f0:.3f} | '
                    f'{1200 * math.log2(f0 / nominal):+.1f} | {(B if fitted else 0):.2e} | {T:.2f}{"" if fitted else " (1st partial)"} | '
                    f'{kgf[key - 1]:.2f} | {diff:+.1f} % |')
    rows += ['', f'Total over the 243 strings: {total:.0f} kgf ({total * KGF / 1000:.1f} kN), the wound strings at their input tension.', '']
    with open(args.out, 'w', encoding='utf8') as fh:
        fh.write('\n'.join(rows))
    d = np.array([p[2] for p in plain])
    print(f'wrote {args.out}')
    print(f'total {total:.0f} kgf; plain wire against the pasted table: mean {d.mean():+.1f} %, range {d.min():+.1f} .. {d.max():+.1f} %; '
          f'{sum(p[3] for p in plain)} of {len(plain)} keys fitted')
    for key in (21, 28, 37, 40, 44, 49, 52, 58, 64, 72, 76, 84, 88):
        p = next(q for q in plain if q[0] == key)
        print(f'  {key:2d} {note(key):4s} measured {p[1]:6.2f} kgf, pasted {kgf[key - 1]:6.2f} ({p[2]:+.1f} %){"" if p[3] else ", 1st partial only"}')


if __name__ == '__main__':
    main()
