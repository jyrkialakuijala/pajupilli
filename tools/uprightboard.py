#!/usr/bin/env python3
"""The upright piano's soundboard as resonances (research/piano_variants.md, 3.1 and 3.4).

The grand's board tool (tools/pianoboard.py: the plate, its ribs and bridges on a 2.5 cm grid,
the lowest 256 resonances and 96 broad ones above, the patches that radiate) run on the board of
a 121 cm upright (Yamaha U1 class):

  - a rectangle 1.42 m wide (y, from the bass end) and 0.95 m high (x, from its top edge down):
    1.35 m^2 (the U1's 1.38), 8.5 mm thinning to 6 mm at the rim;
  - the grain diagonal, along the long bridge; ribs across it 12.8 cm apart (Ege & Boutillon's
    measured upright board: 1.39 x 0.91 m, 9 kg);
  - the bass bridge low on the bass side, carrying the wound keys 1-27 (A0-B2); the long bridge
    from C3 (key 28), 17 cm above the bottom rim, up to the top of the treble 8 cm under the
    top edge (the strings start on the pin block above the board).

    tools/uprightboard.py          the resonances, the bridge's impedance by register
    tools/uprightboard.py -emit    and write src/uprightboard_data.h
"""
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pianoboard as pb  # noqa: E402

W, H = 1.42, 0.95
grand_length = pb.speaking_length
BASS_KEYS = 27


def speaking_length(key):
    """The upright's strings (m): wound 1.19 m at A0 to 0.98 m at B2 (key 27); plain from 1.03 m
    at C3 to the grand's own lengths from C5 (key 52) up (src/upright.cc)."""
    if key <= BASS_KEYS:
        return 1.19 * (0.98 / 1.19) ** ((key - 1) / (BASS_KEYS - 1))
    g = grand_length(52)
    if key >= 52:
        return grand_length(key)
    return 1.03 * (g / 1.03) ** ((key - 28) / 24)


def bridge_point(key):
    """Where key 1..88's strings cross their bridge (x down from the board's top edge, y from the
    bass end, m). The long bridge follows the strings' lengths (a string of length L ends L - 8 cm
    below the top edge, the treble strings near vertical); its lower end bends towards the bass
    side as the tenor strings slant to fit under the bottom rim."""
    if key <= BASS_KEYS:
        t = (key - 1) / (BASS_KEYS - 1)
        return 0.80 - 0.08 * t, 0.10 + 0.26 * t
    L, L0, L1 = speaking_length(key), speaking_length(28), speaking_length(88)
    x = 0.08 + 0.70 * (math.log(L / L1) / math.log(L0 / L1)) ** 1.6
    y = 0.42 + (1.33 - 0.42) * (key - 28) / 60
    return x, y


pb.OUTLINE = [(0, 0), (H, 0), (H, W), (0, W)]
pb.H_MID, pb.H_EDGE = 0.0085, 0.006
pb.RIB_SPACING = 0.128
pb.speaking_length = speaking_length
pb.bridge_point = bridge_point
pb.BRIDGES = (range(1, BASS_KEYS + 1), range(BASS_KEYS + 1, 89))
pb.GRAIN = math.atan2(bridge_point(88)[1] - bridge_point(28)[1], bridge_point(88)[0] - bridge_point(28)[0])


def main():
    if not hasattr(pb, 'BRIDGES') or 'BRIDGES' not in open(pb.__file__).read():
        sys.exit('tools/pianoboard.py has no BRIDGES global yet (the bridges would be the grand\'s 1-20 / 21-88)')
    r = pb.solve()
    tf, tphi, tvol = pb.tail(r)
    f = np.concatenate([r['f'], tf])
    phi = np.concatenate([r['phi'], tphi], axis=1)
    vol = np.concatenate([r['patch_vol'], tvol], axis=1)
    eta = pb.loss_factors(f, r['patch_pos'], vol)
    broad = np.arange(len(f)) >= pb.N_MODES
    widen = np.where(broad, np.maximum(pb.TAIL_ETA / eta, 1.0),
                     1.0 + (pb.EVEN - 1.0) * np.clip(np.log(np.maximum(f, 1.0) / 250.0) / np.log(4.0), 0.0, 1.0))
    vol = vol * np.sqrt(widen)[None, :]
    eta = eta * widen
    print(f"board: {r['area']:.2f} m^2, {r['mass']:.1f} kg with ribs and bridges, {r['n']} grid points, "
          f"grain {math.degrees(pb.GRAIN):.0f} deg, {len(r['patch_pos'])} patches")
    print('lowest resonances (Hz):', ' '.join(f'{x:.0f}' for x in r['f'][:12]))
    print(f"resonance 256: {r['f'][pb.N_MODES - 1]:.0f} Hz; one per {(r['f'][200] - r['f'][50]) / 150:.1f} Hz between 51 and 201")
    print('bridge impedance (kg/s): the median of |Z| over the band')
    print('  band (Hz)      A0     C2     C4     C6     C8')
    for lo, hi in [(50, 100), (100, 300), (300, 1000), (1000, 2500), (2500, 5000), (5000, 9000)]:
        z = pb.impedance(f, phi, np.geomspace(lo, hi, 60), eta)
        print(f'  {lo:5d}-{hi:5d} ' + ' '.join(f'{np.median(z[:, k - 1]):6.0f}' for k in (1, 16, 40, 64, 88)))
    if '-emit' in sys.argv:
        out = ['// Generated by tools/uprightboard.py -emit: the upright\'s soundboard as resonances.',
               '#pragma once', 'namespace pajupilli {', 'namespace uprightboard {',
               f'constexpr int kModes = {len(f)};', 'constexpr int kKeys = 88;',
               f"constexpr int kPatches = {len(r['patch_pos'])};"]

        def arr(name, a, per=8):
            a = np.asarray(a).ravel()
            out.append(f'alignas(64) constexpr float {name}[{len(a)}] = {{')
            for i in range(0, len(a), per):
                out.append('    ' + ' '.join(f'{x:.6e}f,' for x in a[i:i + per]))
            out.append('};')

        arr('kFreq', f)
        arr('kLoss', eta)
        arr('kPhi', phi)
        arr('kPatchPos', r['patch_pos'])  # [patch]: x down from the top edge, y from the bass end (m)
        arr('kPatchVol', vol)
        out += ['}  // namespace uprightboard', '}  // namespace pajupilli', '']
        open(os.path.join(pb.ROOT, 'src', 'uprightboard_data.h'), 'w').write('\n'.join(out))
        print('wrote src/uprightboard_data.h')


if __name__ == '__main__':
    main()
