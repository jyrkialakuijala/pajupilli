#!/usr/bin/env python3
"""The Shigeru Kawai SK-7's soundboard as resonances (research/shigeru_kawai_sk7.md).

The grand's board tool (tools/pianoboard.py: the plate, its ribs and bridges on a 2.5 cm grid,
the lowest 256 resonances and 96 broad ones above, the patches that radiate) run on the board of
a 229 cm grand (the SK-7: 7'6", 157 cm wide, as wide as a concert grand but 45 cm shorter):

  - the concert grand's outline as it is for the first 1.5 m from the belly rail (the treble
    end of every grand is alike), its tail drawn in to end at 1.70 m instead of 2.12 m: 1.77 m^2,
    11.4 kg (the model grand's 1.98 m^2, 12.8 kg). (Shortened evenly to 0.80 instead, or from
    0.9 m on, the treble bridge came near the bent side and single keys of the top two octaves
    fell 10-15 dB into dead spots: 4-5 dB rms off their neighbours where the grand has 2.3.
    SK7_KEEP sets where the drawing-in starts, SK7_EVEN the grand's EVEN, for such trials);
  - the same spruce, 9 mm thinning to 6 mm at the rim (Kawai's tapered solid spruce board), the
    ribs 12.5 cm apart, the bridges as tall;
  - the SK-7's strings (src/sk7.cc): wound 1.66 m at A0 to 1.16 m at E2 (keys 1-20, on the bass
    bridge); plain from 1.44 m at F2 (key 21), 0.76 of the model grand's length there, growing
    to the grand's own lengths from C5 (key 52) up.

    tools/sk7board.py          the resonances, the bridge's impedance by register
    tools/sk7board.py -emit    and write src/sk7board_data.h (that file only; -o PATH: elsewhere)
"""
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pianoboard as pb  # noqa: E402

KEEP = float(os.environ.get('SK7_KEEP', 1.5))  # the outline as the grand's up to here from the belly rail (m)
LENGTH = 1.70  # the board's length (m): the grand's 2.12 less what the shorter case takes from the tail
grand_length = pb.speaking_length


def speaking_length(key):
    """The SK-7's strings (m): as src/sk7.cc builds them."""
    if key <= 20:
        return 1.66 * (1.16 / 1.66) ** ((key - 1) / 19)
    if key >= 52:
        return grand_length(key)
    return grand_length(key) * 0.76 * (1 / 0.76) ** ((key - 21) / 31)


pb.OUTLINE = [(x if x <= KEEP else KEEP + (x - KEEP) * (LENGTH - KEEP) / (2.12 - KEEP), y) for x, y in pb.OUTLINE]
pb.speaking_length = speaking_length
pb.EVEN = float(os.environ.get('SK7_EVEN', pb.EVEN))
pb.GRAIN = math.atan2(pb.bridge_point(88)[1] - pb.bridge_point(21)[1], pb.bridge_point(88)[0] - pb.bridge_point(21)[0])


def main():
    r = pb.solve()
    tf, tphi, tvol = pb.tail(r)
    f = np.concatenate([r['f'], tf])
    phi = np.concatenate([r['phi'], tphi], axis=1)
    vol = np.concatenate([r['patch_vol'], tvol], axis=1)
    eta = pb.loss_factors(f, r['patch_pos'], vol)
    # (as the grand's: the broad ones as broad as the real ones they stand for, the plate's own
    # from 250 Hz up made up to EVEN times broader)
    broad = np.arange(len(f)) >= pb.N_MODES
    widen = np.where(broad, np.maximum(pb.TAIL_ETA / eta, 1.0),
                     1.0 + (pb.EVEN - 1.0) * np.clip(np.log(np.maximum(f, 1.0) / 250.0) / np.log(4.0), 0.0, 1.0))
    vol = vol * np.sqrt(widen)[None, :]
    eta = eta * widen
    print(f"board: {r['area']:.2f} m^2, {r['mass']:.1f} kg with ribs and bridges, {r['n']} grid points, "
          f"grain {math.degrees(pb.GRAIN):.0f} deg, {len(r['patch_pos'])} patches")
    print('lowest resonances (Hz):', ' '.join(f'{x:.0f}' for x in r['f'][:12]))
    print(f"resonance 256: {r['f'][pb.N_MODES - 1]:.0f} Hz; one per {(r['f'][200] - r['f'][50]) / 150:.1f} Hz between 51 and 201")
    print('bridge impedance (kg/s): the median of |Z| over the band')
    print('  band (Hz)      A0     C2     C4     C6     C8')
    for lo, hi in [(50, 100), (100, 300), (300, 1000), (1000, 2500), (2500, 5000), (5000, 9000)]:
        z = pb.impedance(f, phi, np.geomspace(lo, hi, 60), eta)
        print(f'  {lo:5d}-{hi:5d} ' + ' '.join(f'{np.median(z[:, k - 1]):6.0f}' for k in (1, 16, 40, 64, 88)))
    if '-emit' in sys.argv:
        out = ['// Generated by tools/sk7board.py -emit: the Shigeru Kawai SK-7\'s soundboard as resonances.',
               '#pragma once', 'namespace pajupilli {', 'namespace sk7board {',
               f'constexpr int kModes = {len(f)};', 'constexpr int kKeys = 88;',
               f"constexpr int kPatches = {len(r['patch_pos'])};"]

        def arr(name, a, per=8):
            a = np.asarray(a).ravel()
            out.append(f'alignas(64) constexpr float {name}[{len(a)}] = {{')
            for i in range(0, len(a), per):
                out.append('    ' + ' '.join(f'{x:.6e}f,' for x in a[i:i + per]))
            out.append('};')

        arr('kFreq', f)
        arr('kLoss', eta)
        arr('kPhi', phi)
        arr('kPatchPos', r['patch_pos'])  # [patch]: x from the belly rail, y from the spine (m)
        arr('kPatchVol', vol)
        out += ['}  // namespace sk7board', '}  // namespace pajupilli', '']
        path = sys.argv[sys.argv.index('-o') + 1] if '-o' in sys.argv else os.path.join(pb.ROOT, 'src', 'sk7board_data.h')
        open(path, 'w').write('\n'.join(out))
        print('wrote', path)


if __name__ == '__main__':
    main()
