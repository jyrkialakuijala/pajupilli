#!/usr/bin/env python3
"""Loudness of every instrument, and the trims that bring them to a common level.

    tools/levels.py            measure and print (with the present trims in force)
    tools/levels.py -emit      measure without trims and write src/levels_data.h

Each instrument plays three notes of its range (a quarter, a half and three quarters up) at its
default dynamics with `flute -note`, 1.5 s each. Loudness is measured as broadcast meters do
(ITU-R BS.1770: a high shelf and a high-pass, then the mean square: LUFS, ungated), over each
note's loudest second, and averaged over the three notes. The trim brings each instrument to the
median, by at most +-18 dB. Percussive and plucked sounds die away within the second: they read
lower than a held note of the same peak, and so come out a little louder: as on a mixing desk.
"""
import math
import os
import re
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

import numpy as np
from scipy.io import wavfile
from scipy.signal import lfilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FLUTE = os.path.join(ROOT, 'flute')


def k_weight(x, fs):
    """BS.1770 K-weighting: a +4 dB shelf above ~1.7 kHz, then a 38 Hz high-pass."""
    f0, g, q = 1681.974450955533, 3.999843853973347, 0.7071752369554196
    k = math.tan(math.pi * f0 / fs)
    vh, vb = 10 ** (g / 20), (10 ** (g / 20)) ** 0.4996667741545416
    a0 = 1 + k / q + k * k
    b = [(vh + vb * k / q + k * k) / a0, 2 * (k * k - vh) / a0, (vh - vb * k / q + k * k) / a0]
    a = [1, 2 * (k * k - 1) / a0, (1 - k / q + k * k) / a0]
    x = lfilter(b, a, x)
    f0, q = 38.13547087602444, 0.5003270373238773
    k = math.tan(math.pi * f0 / fs)
    a0 = 1 + k / q + k * k
    return lfilter([1, -2, 1], [1, 2 * (k * k - 1) / a0, (1 - k / q + k * k) / a0], x)


def names():
    out = subprocess.run([FLUTE, '-inst', 'nosuch'], capture_output=True, text=True)
    m = re.search(r'-inst: (.*)', out.stdout + out.stderr)
    return [n.strip() for n in m.group(1).split(',')]


def measure(inst, env):
    out = subprocess.run([FLUTE, '-inst', inst, '-note', '0'], capture_output=True, text=True, env=env)
    m = re.search(r'plays MIDI (\d+)\.\.(\d+)', out.stdout + out.stderr)
    lo, hi = int(m.group(1)), int(m.group(2))
    if inst == 'double-bass':
        hi = 67  # (above: harmonics)
    vals = []
    with tempfile.TemporaryDirectory() as d:
        for share in (0.25, 0.5, 0.75):
            note = round(lo + share * (hi - lo))
            path = os.path.join(d, 'n.wav')
            subprocess.run([FLUTE, '-inst', inst, '-note', str(note), '-secs', '1.5', '-o', path],
                           capture_output=True, text=True, env=env)
            if not os.path.exists(path):
                continue
            fs, x = wavfile.read(path)
            x = x.astype(float)
            if x.ndim > 1:
                x = x.mean(1)
            y = k_weight(x, fs) ** 2
            n = min(len(y), fs)
            c = np.cumsum(np.concatenate([[0], y]))
            ms = (c[n:] - c[:-n]).max() / n
            if ms > 1e-12:
                vals.append(-0.691 + 10 * math.log10(ms))
            os.remove(path)
    return inst, (float(np.mean(vals)) if vals else None)


def main():
    emit = '-emit' in sys.argv
    env = dict(os.environ)
    if emit:
        env['PJ_NOLEVELS'] = '1'
    ns = names()
    with ThreadPoolExecutor(4) as ex:  # (a few at a time: the machine is shared)
        res = list(ex.map(lambda n: measure(n, env), ns))
    ok = {n: v for n, v in res if v is not None}
    med = float(np.median(list(ok.values())))
    print(f'median {med:.1f} LUFS' + (' (without trims)' if emit else ' (with the trims in force)'))
    for n, v in res:
        print(f'  {n:18s} ' + (f'{v:6.1f} LUFS  ({v - med:+5.1f})' if v is not None else 'silent'))
    if emit:
        lines = ['// Generated by tools/levels.py -emit: each instrument\'s trim (dB) to a common loudness',
                 '// (BS.1770, three notes of its range at default dynamics; at most +-18 dB).',
                 '#pragma once', 'namespace pajupilli {',
                 'struct LevelTrim { const char* name; float db; };',
                 'constexpr LevelTrim kLevelTrims[] = {']
        for n, v in res:
            if v is not None:
                lines.append(f'    {{"{n}", {max(-18.0, min(18.0, med - v)):.1f}f}},')
        lines += ['};', '}  // namespace pajupilli', '']
        open(os.path.join(ROOT, 'src', 'levels_data.h'), 'w').write('\n'.join(lines))
        print('wrote src/levels_data.h')


if __name__ == '__main__':
    main()
