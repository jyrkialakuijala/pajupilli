#!/usr/bin/env python3
"""The bowed bass's notes, evened by ear.

    tools/bowlevels.py          measure and print (with the present table in force)
    tools/bowlevels.py -emit    measure without it and write src/bowlevels_data.h

A bass does not answer every note alike: one sits on a resonance of the body, the next between
two, another is shared with an open string that rings along and holds the bridge. A bassist hears
it and draws the bow a little faster or slower. Here: every note (E1 .. C6) is bowed for 2 s at
default dynamics, its loudness measured as in tools/levels.py (BS.1770) over 0.8 .. 1.6 s; the
table is each note's level against the running median of its neighbours (+-3 notes), which the
player (BowPlayer) answers with 70 % of it in bow speed, at most +-6 dB.
"""
import math
import os
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor

import numpy as np
from scipy.io import wavfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from levels import FLUTE, ROOT, k_weight  # noqa: E402

LO, HI = 28, 84


def measure(note, env):
    with tempfile.TemporaryDirectory() as d:
        path = os.path.join(d, 'n.wav')
        subprocess.run([FLUTE, '-inst', 'contrabass', '-note', str(note), '-secs', '2', '-o', path],
                       capture_output=True, text=True, env=env)
        fs, x = wavfile.read(path)
    x = x.astype(float)
    if x.ndim > 1:
        x = x.mean(1)
    y = k_weight(x, fs)[int(0.8 * fs):int(1.6 * fs)] ** 2
    return -0.691 + 10 * math.log10(max(y.mean(), 1e-20))


def main():
    emit = '-emit' in sys.argv
    env = dict(os.environ)
    if emit:
        env['PJ_ARCO_EVEN'] = '0'
    with ThreadPoolExecutor(4) as ex:  # (a few at a time: the machine is shared)
        lv = np.array(list(ex.map(lambda n: measure(n, env), range(LO, HI + 1))))
    rel = np.array([lv[i] - np.median(lv[max(0, i - 3):i + 4]) for i in range(len(lv))])
    print('note: level against its neighbours (dB)' + (' (without the table)' if emit else ' (with the table in force)'))
    print(' '.join(f'{v:+.0f}' for v in rel))
    print(f'spread: std {rel.std():.1f} dB, largest {np.abs(rel).max():.1f} dB; whole range std {(lv - np.median(lv)).std():.1f} dB')
    if emit:
        lines = ['// Generated by tools/bowlevels.py -emit: each bowed note of the contrabass against its',
                 '// neighbours (dB; MIDI %d .. %d), for the player to even out with the bow.' % (LO, HI),
                 '#pragma once', 'namespace pajupilli {', 'constexpr int kBowLevelLo = %d;' % LO,
                 'constexpr float kBowLevels[] = {']
        for i in range(0, len(rel), 12):
            lines.append('    ' + ' '.join(f'{v:.1f}f,' for v in rel[i:i + 12]))
        lines += ['};', '}  // namespace pajupilli', '']
        open(os.path.join(ROOT, 'src', 'bowlevels_data.h'), 'w').write('\n'.join(lines))
        print('wrote src/bowlevels_data.h')


if __name__ == '__main__':
    main()
