#!/usr/bin/env python3
"""The Hohner Clavinet D6's tone switches as filters (research/clavinet.md, 7.1-7.3).

From the tone node X to ground the four elements stand in series, each shorted by its rocker
switch until it is pressed:

    Soft       30 k || 0.1 uF
    Medium     10 k || 15 nF
    Treble     (2 H + 60 ohm) || 4.7 nF      the "twang": a resonance near 1.6 kHz
    Brilliant  0.6 H + 20 ohm

X is fed from stage 1's collector (51 k) and loads into stage 2 through 30 k + 10 nF (its input
about 16 k). For the 15 settings (none pressed: silent) the transfer to stage 2's base is

    H = Rin Zs Dl / (Rs Zs Dl + Rs Nl Ds + Zs Nl)      (Zs = Ns / Ds the elements in series,
                                                       Zload = Nl / Dl)

as a ratio of polynomials in s, taken to 48 kHz by the bilinear transform (prewarped at the
Treble resonance) and split into second-order sections. The settings keep their levels
against each other (up to 20 dB apart: on the instrument the volume is reset on switching);
the loudest's peak is 0 dB.

The E7's (a 12 k source, a 77 k load) is written beside the D6's.

    tools/clavtone.py          print each setting's response at a few frequencies
    tools/clavtone.py -emit    and write src/clavtone_data.h
"""
import os
import sys

import numpy as np
from scipy import signal

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FS = 48000
RS, RIN, RSER, CSER = 51e3, 16e3, 30e3, 10e-9

# Each element as (numerator, denominator) in s, highest power first (numpy's order).
def rc_par(r, c):
    return np.array([r]), np.array([r * c, 1.0])


def lc_par(l, r, c):  # (sL + r) || 1/(sC) = (sL + r) / (s^2 LC + s rC + 1)
    return np.array([l, r]), np.array([l * c, r * c, 1.0])


ELEMENTS = {'S': rc_par(30e3, 0.1e-6), 'M': rc_par(10e3, 15e-9), 'T': lc_par(2.0, 60.0, 4.7e-9),
            'B': (np.array([0.6, 20.0]), np.array([1.0]))}
NAMES = 'SMTB'


def series(mask):
    num, den = np.array([0.0]), np.array([1.0])
    for b, k in enumerate(NAMES):
        if mask >> b & 1:
            n, d = ELEMENTS[k]
            num = np.polyadd(np.polymul(num, d), np.polymul(n, den))
            den = np.polymul(den, d)
    return num, den


def transfer(mask, rs=RS, rin=RIN):
    ns, ds = series(mask)
    nl = np.array([(RSER + rin) * CSER, 1.0])  # Zload = (1 + s C (Rser + Rin)) / (s C)
    dl = np.array([CSER, 0.0])
    num = rin * np.polymul(ns, dl)
    den = np.polyadd(np.polyadd(rs * np.polymul(ns, dl), rs * np.polymul(nl, ds)), np.polymul(ns, nl))
    return num, den


def digital(mask, rs=RS, rin=RIN):
    b, a = transfer(mask, rs, rin)
    sos = signal.tf2sos(*signal.bilinear(b, a, FS), pairing='nearest')
    return sos


def response(sos, f):
    _, h = signal.sosfreqz(sos, worN=np.asarray(f, float), fs=FS)
    return 20 * np.log10(np.abs(h) + 1e-30)


# The E7: the same network, fed from a 12 k collector (its stage 1), into a stage 2 of about
# 77 k input (research/clavinet.md 7.4): the network shapes the sound a little less.
MODELS = (('kSos', 'the D6', RS, RIN), ('kSosE7', 'the E7', 12e3, 77e3))


def main():
    f = [100, 400, 1000, 1640, 3000, 5000, 12000]
    grid = np.geomspace(30, 20000, 2000)
    out = ['// Generated by tools/clavtone.py -emit: the Clavinet\'s tone switches (research/clavinet.md 7.3),',
           '// per setting (bits: 1 Soft, 2 Medium, 4 Treble, 8 Brilliant) second-order sections at 48 kHz',
           '// (b0 b1 b2 a1 a2; unused sections pass), each model\'s loudest setting\'s peak 0 dB.',
           '#pragma once', 'namespace pajupilli {', 'namespace clavtone {']
    sets = {name: {m: digital(m, rs, rin) for m in range(1, 16)} for name, _, rs, rin in MODELS}
    n = max(len(s) for ss in sets.values() for s in ss.values())
    out.append(f'constexpr int kSections = {n};')
    for name, what, rs, rin in MODELS:
        ss = sets[name]
        peak = max(response(s, grid).max() for s in ss.values())
        print(f'{what} (source {rs / 1e3:.0f} k, load {rin / 1e3:.0f} k)')
        print('setting  ' + ' '.join(f'{x:>7}' for x in f) + '   (dB; the loudest peak 0 dB)')
        for m, s in ss.items():
            nm = '+'.join(NAMES[b] for b in range(4) if m >> b & 1)
            print(f'{nm:8s} ' + ' '.join(f'{v - peak:7.1f}' for v in response(s, f)))
        g = 10 ** (-peak / 20)
        out += [f'// {what}', f'constexpr double {name}[16][{n}][5] = {{', '    {}, // none pressed: silent']
        for m in range(1, 16):
            s = ss[m].copy()
            s[0, :3] *= g
            rows = [f'{{{r[0]:.12e}, {r[1]:.12e}, {r[2]:.12e}, {r[4]:.12e}, {r[5]:.12e}}}' for r in s]
            rows += ['{1, 0, 0, 0, 0}'] * (n - len(s))
            out.append('    {' + ', '.join(rows) + '},')
        out.append('};')
    out += ['}  // namespace clavtone', '}  // namespace pajupilli', '']
    if '-emit' in sys.argv:
        open(os.path.join(ROOT, 'src', 'clavtone_data.h'), 'w').write('\n'.join(out))
        print('wrote src/clavtone_data.h')


if __name__ == '__main__':
    main()
