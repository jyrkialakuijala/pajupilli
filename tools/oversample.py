#!/usr/bin/env python3
"""The guitar amp's oversampling filters (src/guitaramp.cc): 8th-order elliptic low-passes, flat
(0.1 dB) to 19 kHz, 80 dB down from 26 kHz: they remove the images of the upsampling and, before
decimation, what the distortion made above the audio band. One at 4 x 48 kHz (the overdriven
amps), one at 2 x 48 kHz (the high-gain amp, whose stages also antialias their own curves: what
folds at 2x lands above 22 kHz or is 80 dB down).

    tools/oversample.py        write src/oversample_data.h
"""
import os
from scipy.signal import ellip, ellipord

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def design(fs):
    n, wn = ellipord(19000, 26000, 0.1, 80, fs=fs)
    return ellip(n, 0.1, 80, wn, output='sos', fs=fs)


sos4, sos2 = design(4 * 48000), design(2 * 48000)
assert len(sos4) == len(sos2)
lines = ['// Generated by tools/oversample.py: the guitar amp\'s oversampling low-passes (8th-order',
         '// elliptic at 192 kHz (kSos) and at 96 kHz (kSos2): 0.1 dB to 19 kHz, -80 dB from 26 kHz),',
         '// biquads b0 b1 b2 a1 a2.',
         '#pragma once', 'namespace pajupilli {', 'namespace oversample {',
         f'constexpr int kSections = {len(sos4)};']
for name, sos in (('kSos', sos4), ('kSos2', sos2)):
    lines.append(f'constexpr double {name}[kSections][5] = {{')
    for s in sos:
        lines.append('    {%s},' % ', '.join('%.17g' % v for v in (s[0], s[1], s[2], s[4], s[5])))
    lines.append('};')
lines += ['}  // namespace oversample', '}  // namespace pajupilli', '']
open(os.path.join(ROOT, 'src', 'oversample_data.h'), 'w').write('\n'.join(lines))
print('wrote src/oversample_data.h')
