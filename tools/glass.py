#!/usr/bin/env python3
"""The glass instrument's plate (src/lead.cc, -inst fx-crystal, GM 99): its modes.

A 16 x 16 plate wrapped into a torus (both pairs of opposite edges joined:
periodic in x and in y, no boundary anywhere), bending stiffness uniform
(Kirchhoff: K = D L^2, L the periodic 5-point Laplacian), mass varying along x
(rho(x): a heavier and a lighter band round the torus). Its modes solve
K phi = w^2 M phi (M = diag(rho)); the rigid motion (w = 0) is left out.

    tools/glass.py          print the lowest modes: ratios to the first, degeneracies
    tools/glass.py -emit    write src/glass_data.h: the ratios and the mass-normalised
                            shapes on the grid (x 16, so the values are about 1)

With mass along x only, the plate keeps its symmetries in y: every mode with
a wave along y comes as a pair (its cosine and sine), at one frequency.
"""
import os
import sys

import numpy as np

N = 16
MODES = 64
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rho(x):
    # Heavier on one side of the ring, a second band lighter: 0.5 .. 1.7.
    return 1 + 0.5 * np.sin(2 * np.pi * x / N) + 0.2 * np.cos(4 * np.pi * x / N + 1.0)


def modes():
    n = N * N
    idx = lambda x, y: (x % N) * N + (y % N)
    L = np.zeros((n, n))
    for x in range(N):
        for y in range(N):
            i = idx(x, y)
            L[i, i] = -4
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                L[i, idx(x + dx, y + dy)] += 1
    K = L @ L
    m = np.repeat(rho(np.arange(N)), N)  # cell (x, y) at index x N + y
    s = 1 / np.sqrt(m)
    A = s[:, None] * K * s[None, :]
    lam, psi = np.linalg.eigh(A)
    order = np.argsort(lam)
    lam, psi = lam[order], psi[:, order]
    phi = s[:, None] * psi  # mass-normalised: phi^T M phi = 1
    w = np.sqrt(np.maximum(lam, 0))
    keep = w > 1e-6 * w.max()
    w, phi = w[keep][:MODES], phi[:, keep][:, :MODES]
    return w / w[0], phi * N


def main():
    ratios, phi = modes()
    if '-emit' in sys.argv:
        path = os.path.join(ROOT, 'src', 'glass_data.h')
        with open(path, 'w') as f:
            f.write('// Generated by tools/glass.py -emit: a 16 x 16 torus plate, mass varying along x\n')
            f.write('// (rho = 1 + 0.5 sin(2 pi x/16) + 0.2 cos(4 pi x/16 + 1)): its lowest modes, the\n')
            f.write('// frequency ratios to the first, the mass-normalised shapes (x 16) at cell [x][y].\n')
            f.write('#pragma once\nnamespace pajupilli {\n')
            f.write(f'constexpr int kGlassN = {N}, kGlassModes = {len(ratios)};\n')
            f.write('constexpr float kGlassRatio[kGlassModes] = {' + ', '.join(f'{r:.6f}f' for r in ratios) + '};\n')
            f.write('constexpr float kGlassShape[kGlassModes][kGlassN][kGlassN] = {\n')
            for k in range(len(ratios)):
                g = phi[:, k].reshape(N, N)
                rows = ', '.join('{' + ', '.join(f'{v:.5f}f' for v in g[x]) + '}' for x in range(N))
                f.write(f'    {{{rows}}},\n')
            f.write('};\n}  // namespace pajupilli\n')
        print('wrote', path)
        return
    print('mass along x:', ' '.join(f'{v:.2f}' for v in rho(np.arange(N))))
    print('lowest modes (ratio to the first):')
    print(' '.join(f'{r:.3f}' for r in ratios[:40]))


if __name__ == '__main__':
    main()
